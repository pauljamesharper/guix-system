"""Omarchy themes -> mangobutter themes (see omarchy-themes.nix).

usage: omarchy-themes.py <omarchy>/themes <omarchy-themes-backgrounds> <out>
"""

import os
import re
import shutil
import subprocess
import sys
import tomllib

themes_dir, bg_dir, out = sys.argv[1:4]
conf_dir = os.path.join(out, "share/butter-themes")
wall_dir = os.path.join(out, "share/wallpapers")
prev_dir = os.path.join(out, "share/omarchy-themes")
for d in (conf_dir, wall_dir, prev_dir):
    os.makedirs(d, exist_ok=True)

HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
IMAGE = (".jpg", ".jpeg", ".png", ".webp")
NAMES = {"rose-pine": "Rosé Pine", "retro-82": "Retro-82"}


def pretty(theme):
    return NAMES.get(theme, " ".join(w.capitalize() for w in theme.split("-")))


def wall_order(name):
    # numbered ones in order, the plain Omarchy logo ("omarchy.webp") last
    return (not name[0].isdigit(), name)


sections = []
for theme in sorted(os.listdir(themes_dir)):
    toml = os.path.join(themes_dir, theme, "colors.toml")
    if not os.path.isfile(toml):
        continue
    with open(toml, "rb") as f:
        c = tomllib.load(f)

    def col(*keys):
        for k in keys:
            v = c.get(k)
            if isinstance(v, str) and HEX.match(v):
                return v.lower()
        raise SystemExit(f"{theme}: no color for {keys[0]}")

    accent = col("accent")
    blue = col("blue")
    fields = {
        "bg": col("background"),
        "bg_alt": col("lighter_background", "selection"),
        "fg": col("foreground"),
        "border": col("selection", "lighter_background"),
        "primary": accent,
        # a second color that isn't the accent again
        "secondary": blue if blue != accent else col("cyan"),
        "alert": col("red"),
        "disabled": col("muted", "dark_foreground"),
    }
    terminal = [
        col("background"),
        col("red"),
        col("green"),
        col("yellow"),
        col("blue"),
        col("magenta"),
        col("cyan"),
        col("foreground"),
        col("muted", "dark_foreground"),
        col("bright_red", "red"),
        col("bright_green", "green"),
        col("bright_yellow", "yellow"),
        col("bright_blue", "blue"),
        col("bright_magenta", "magenta"),
        col("bright_cyan", "cyan"),
        col("bright_foreground", "foreground"),
    ]

    walls = []
    src = os.path.join(bg_dir, theme)
    if os.path.isdir(src):
        for name in sorted(os.listdir(src), key=wall_order):
            stem, ext = os.path.splitext(name)
            if ext.lower() not in IMAGE:
                continue
            dest_name = f"omarchy-{theme}-{stem}.jpg"
            dest = os.path.join(wall_dir, dest_name)
            if ext.lower() in (".jpg", ".jpeg"):
                shutil.copyfile(os.path.join(src, name), dest)
            else:
                subprocess.run(
                    ["magick", os.path.join(src, name), "-quality", "92", dest],
                    check=True,
                )
            walls.append(dest_name)

    preview = os.path.join(themes_dir, theme, "preview.png")
    if os.path.isfile(preview):
        os.makedirs(os.path.join(prev_dir, theme), exist_ok=True)
        shutil.copyfile(preview, os.path.join(prev_dir, theme, "preview.png"))

    lines = [f"[{theme}]", f"name = {pretty(theme)}", f"mode = {c.get('mode', 'dark')}"]
    lines.append("wallpapers = " + " ".join(walls))
    lines += [f"{k} = {v}" for k, v in fields.items()]
    lines.append("terminal = " + " ".join(terminal))
    sections.append("\n".join(lines))

with open(os.path.join(conf_dir, "omarchy.conf"), "w") as f:
    f.write("# Omarchy's themes, generated by omarchy-themes.nix\n\n")
    f.write("\n\n".join(sections) + "\n")
print(f"{len(sections)} themes")
